// Generates lib/core/schema_generated.dart from the OpenTodo repository's
// generated op schema (web/src/generated/opSchema.ts), so the Flutter client
// carries the same row defaults and content-field list as the web app and the
// server. Run from the project root:
//   node tool/sync_schema.mjs [path-to-OpenTodo-checkout]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const repo = resolve(process.argv[2] ?? '../OpenTodo')
const src = readFileSync(resolve(repo, 'web/src/generated/opSchema.ts'), 'utf8')

/** The object literal of `export const NAME = { … }`, braces balanced. */
function objectOf(name) {
  const start = src.indexOf(`export const ${name}`)
  if (start < 0) throw new Error(`${name} not found in opSchema.ts`)
  let i = src.indexOf('{', src.indexOf('=', start))
  let depth = 0
  const from = i
  for (; i < src.length; i++) {
    if (src[i] === '{') depth++
    else if (src[i] === '}') { depth--; if (depth === 0) break }
  }
  let body = src.slice(from, i + 1)
  body = body.replace(/\s*satisfies Omit<[^>]+>/g, '') // TS-only assertion
  return eval(`(${body})`)
}

const defaults = objectOf('OP_DEFAULTS')
const content = objectOf('OP_CONTENT_FIELDS')

/** A JSON value as a Dart literal. */
function dart(v) {
  if (v === null) return 'null'
  if (typeof v === 'string') return `'${v.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n')}'`
  if (typeof v === 'number' || typeof v === 'boolean') return String(v)
  if (Array.isArray(v)) return `[${v.map(dart).join(', ')}]`
  const entries = Object.entries(v).map(([k, x]) => `'${k}': ${dart(x)}`)
  return `{${entries.join(', ')}}`
}

const out = `// Generated by tool/sync_schema.mjs from OpenTodo's web/src/generated/opSchema.ts.
// DO NOT EDIT: run the script again after the server's op schema changes.

/// The row a field op creates when its entity is new (OP_DEFAULTS): one key per
/// op field, a family (fields.<id>, appends.<id>, reactions.<id>) in one key
/// named after its prefix.
const Map<String, Map<String, Object?>> opDefaults = {
${Object.entries(defaults).map(([e, row]) => `  '${e}': ${dart(row)},`).join('\n')}
};

/// User-written fields a device encrypts for an account with end-to-end
/// encryption (OP_CONTENT_FIELDS).
const Map<String, List<String>> opContentFields = {
${Object.entries(content).map(([e, fields]) => `  '${e}': [${fields.map((f) => `'${f}'`).join(', ')}],`).join('\n')}
};
`
mkdirSync(resolve('lib/core'), { recursive: true })
writeFileSync(resolve('lib/core/schema_generated.dart'), out)
console.log(`schema_generated.dart: ${Object.keys(defaults).length} entities, ${Object.values(content).flat().length} content fields`)
